'use strict';
// ───────────────────────────────────────────────────────────────────────────
//  МОДЕЛЬ ДОСТУПА — единственное место, где решается «видно или нет».
//  Страницы не знают про уровни: они спрашивают can() и рисуют то, что дали.
//  Добавить четвёртый тариф = поменять числа здесь, а не трогать страницы.
// ───────────────────────────────────────────────────────────────────────────

const LEVELS = [
  { n: 0, name: 'Гость',         tagline: 'Бесплатно' },
  { n: 1, name: 'Читатель',      tagline: 'Уровень 1' },
  { n: 2, name: 'Практик',       tagline: 'Уровень 2' },
  { n: 3, name: 'Исследователь', tagline: 'Уровень 3' },
];

// Матрица доступа: минимальный уровень для каждой точки доступа.
// Это значения по умолчанию. У конкретной статьи их можно переопределить
// в шапке файла (например, body: 0 — статья открыта всем).
const POINTS = {
  article: {
    preview:      0, // заголовок, вступление, оглавление
    body:         1, // полный текст
    video_hint:   1, // пометка «по теме есть видео»
    extras:       2, // панель связей, связанные материалы, поля к заметке
    video_player: 2, // плеер видео внутри статьи
  },
  video: {
    on_site:    0, // несколько видео на страницах сайта
    in_list:    1, // каталог всех видео
    in_article: 2, // плеер внутри статьи
    exclusive:  3, // эксклюзивная лекция
  },
  course: { listed: 1, available: 3 },
  quiz:   { available: 0 },
};

// ── Ядро: одна функция на весь сайт ────────────────────────────────────────
function can(user, required) {
  if (required === undefined || required === null) return true;
  return (user.level || 0) >= required;
}

// Точечное разрешение: конкретный объект открыт человеку независимо от уровня
// (промокод на подборку, компенсация за сбой, пробный доступ).
function hasGrant(user, itemId) {
  return Boolean(itemId) && (user.grants || []).includes(itemId);
}

// Проверка с учётом точечного разрешения — используется для статей и видео.
function canItem(user, required, itemId) {
  return can(user, required) || hasGrant(user, itemId);
}

// Почему закрыто — человеческим языком, для панели-заглушки.
function reason(required) {
  if (required === 0) return 'Доступно всем';
  return 'Нужен уровень ' + required;
}

function levelName(n) {
  const l = LEVELS[n];
  return l ? l.name : 'Гость';
}

module.exports = { LEVELS, POINTS, can, canItem, hasGrant, reason, levelName };
